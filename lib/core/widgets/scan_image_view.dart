/// Displays a scan photo from an asset (sample), a device file, or a web
/// blob URL. Sample images are always labelled as such.
class ScanImageView extends StatelessWidget {
  const ScanImageView({
    super.key,
    required this.path,
    this.isSample = false,
    this.quarterTurns = 0,
    this.radius = AppRadius.lg,
    this.showSampleLabel = true,
    this.overlay,
  });

  final String path;
  final bool isSample;
  final int quarterTurns;
  final double radius;
  final bool showSampleLabel;

  /// Drawn over the image (e.g. the demo heatmap).
  final Widget? overlay;

  static ImageProvider providerFor(String path, {required bool isAsset}) {
    if (isAsset) return AssetImage(path);
    if (kIsWeb) return NetworkImage(path);
    return FileImage(File(path));
  }

  @override
  Widget build(BuildContext context) {
    return ClipRRect(
      borderRadius: BorderRadius.circular(radius),
      child: Stack(
        fit: StackFit.expand,
        children: [
          RotatedBox(
            quarterTurns: quarterTurns,
            child: Image(
              image: providerFor(path, isAsset: isSample),
              fit: BoxFit.cover,
              errorBuilder: (context, error, stack) => Container(
                color: AppColors.skin,
                alignment: Alignment.center,
                child: const Icon(Icons.broken_image_outlined,
                    color: AppColors.skinBorder, size: 40),
              ),
            ),
          ),
          ?overlay,
          if (isSample && showSampleLabel)
            Positioned(
              left: 10,
              top: 10,
              child: Container(
                padding:
                    const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                decoration: BoxDecoration(
                  color: Colors.black.withValues(alpha: 0.45),
                  borderRadius: BorderRadius.circular(AppRadius.pill),
                ),
                child: Text('Sample image',
                    style: AppTextStyles.small.copyWith(
                        color: Colors.white, fontWeight: FontWeight.w600)),
              ),
            ),
        ],
      ),
    );
  }
}


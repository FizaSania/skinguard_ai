import 'skin_scan.dart';

/// One concern reported for one analysed area.
class ConcernFinding {
  const ConcernFinding({
    required this.concern,
    required this.confidence,
    required this.region,
    required this.explanation,
    this.heatmapReference,
  });

  /// e.g. "Acne". Label set will come from the ML model's classes.
  final String concern;

  /// 0.0 – 1.0
  final double confidence;

  /// Null means the finding applies to the full-face image.
  final FaceRegion? region;

  final String explanation;

  // FUTURE HEATMAP INTEGRATION: URL / path of the Grad-CAM (or similar)
  // heatmap generated by the ML pipeline for this finding.
  final String? heatmapReference;

  String get regionLabel => region?.label ?? 'Full Face';

  int get confidencePercent => (confidence * 100).round();
}

/// Result of analysing one [ScanSession].
class AnalysisResult {
  const AnalysisResult({
    required this.scanId,
    required this.findings,
    required this.generatedAt,
    required this.isDemo,
    this.modelVersion,
  });

  final String scanId;
  final List<ConcernFinding> findings;
  final DateTime generatedAt;

  /// True for every result produced by the mock service. The UI shows a
  /// "Demo result" badge whenever this is true.
  final bool isDemo;

  // FUTURE ML INTEGRATION: filled with the version string returned by the API.
  final String? modelVersion;

  ConcernFinding? get primary => findings.isEmpty
      ? null
      : (List.of(findings)
            ..sort((a, b) => b.confidence.compareTo(a.confidence)))
          .first;

  Set<String> get concerns => findings.map((f) => f.concern).toSet();
}

enum AnalysisStage {
  detecting('Detecting skin concerns'),
  analyzing('Analyzing image'),
  generating('Generating result');

  const AnalysisStage(this.label);
  final String label;
}

/// Progress event emitted while an analysis runs.
class AnalysisProgress {
  const AnalysisProgress(this.stage, {this.result});

  final AnalysisStage stage;

  /// Non-null on the final event.
  final AnalysisResult? result;

  bool get isDone => result != null;
}
